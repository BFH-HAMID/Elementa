#!/usr/bin/env python3
"""Add twenty complete guided practicals to the Elementa Chemistry Lab.

The twenty practicals below fill the gaps a student meets in the NCTB chemistry
syllabus: gas preparation and testing, redox, ion identification, hydrolysis,
thermal stability and the reactivity of metals. Every one of them is seeded on
the virtual bench (``setup.vessels``), walked through with auto-checked steps and
finished with a quiz, so it behaves exactly like the eleven that were already in
``data/experiments.json``.

The script is idempotent: an experiment whose ``slug`` already exists is left
untouched, and the top-level ``count`` is recomputed from the list.

Run it from the repository root:

    python3 scripts/add-chemistry-lab-practicals.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "data" / "experiments.json"


def vessel(apparatus_id: str, label_en: str, label_bn: str, portions: list[tuple[str, float]]) -> dict:
    """One station on the bench: glassware plus what is already in it."""
    return {
        "apparatusId": apparatus_id,
        "label_en": label_en,
        "label_bn": label_bn,
        "portions": [{"chemicalId": chemical_id, "mL": amount} for chemical_id, amount in portions],
    }


def step(order: int, text_en: str, text_bn: str, check: dict) -> dict:
    """One auto-checked instruction."""
    return {"order": order, "text_en": text_en, "text_bn": text_bn, "check": check}


def quiz(question_en, question_bn, options_en, options_bn, answer, explain_en, explain_bn) -> dict:
    """One viva question with its answer and explanation."""
    return {
        "question_en": question_en,
        "question_bn": question_bn,
        "options_en": options_en,
        "options_bn": options_bn,
        "answer": answer,
        "explain_en": explain_en,
        "explain_bn": explain_bn,
    }


def experiment(order, slug, level, duration, apparatus, chemicals, vessels, steps, safety, expected, quizzes, tags,
               title_en, title_bn, aim_en, aim_bn) -> dict:
    """Assemble an experiment with the same key order as the existing dataset."""
    return {
        "order": order,
        "level": level,
        "durationMinutes": duration,
        "apparatus": apparatus,
        "chemicals": chemicals,
        "setup": {"vessels": vessels},
        "steps": steps,
        "safety": safety,
        "expectedReactions": expected,
        "quiz": quizzes,
        "tags": tags,
        "slug": slug,
        "title_en": title_en,
        "title_bn": title_bn,
        "aim_en": aim_en,
        "aim_bn": aim_bn,
    }


