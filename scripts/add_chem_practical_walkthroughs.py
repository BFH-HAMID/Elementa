def main():
    chem_path = os.path.join(ROOT, 'data', 'chemicals.json')
    with open(chem_path, encoding='utf-8') as fh:
        chem = json.load(fh, object_pairs_hook=collections.OrderedDict)
    existing = {c['id'] for c in chem['chemicals']}
    for c in NEW_CHEMICALS:
        if c['id'] in existing:
            continue
        c = dict(c)
        c.setdefault('shelf', True)
        ordered = collections.OrderedDict()
        for key in ['shelf', 'hazard', 'opacity', 'soluble', 'precipitate', 'amphoteric', 'id', 'formula',
                    'name_en', 'name_bn', 'category', 'state', 'color', 'molarMass', 'concentrationM',
                    'acidity', 'notes_en', 'notes_bn']:
            ordered[key] = c[key]
        chem['chemicals'].append(ordered)
    chem['count'] = len(chem['chemicals'])
    chem['shelfCount'] = sum(1 for c in chem['chemicals'] if c.get('shelf'))
    with open(chem_path, 'w', encoding='utf-8') as fh:
        json.dump(chem, fh, ensure_ascii=False, indent=2)
        fh.write('\n')
    print('chemicals:', chem['count'], 'shelf:', chem['shelfCount'])

    exp_path = os.path.join(ROOT, 'data', 'experiments.json')
    with open(exp_path, encoding='utf-8') as fh:
        data = json.load(fh, object_pairs_hook=collections.OrderedDict)
    exps = data['experiments']
    known = {e['slug'] for e in exps}
    for spec in EXPERIMENTS:
        if spec['slug'] in known:
            continue
        steps = []
        for i, st in enumerate(spec['steps'], start=1):
            step = collections.OrderedDict()
            step['order'] = i
            step['text_en'] = st['text_en']
            step['text_bn'] = st['text_bn']
            step['check'] = st['check']
            steps.append(step)
        entry = collections.OrderedDict([
            ('order', spec['order']),
            ('level', spec['level']),
            ('durationMinutes', spec['duration']),
            ('apparatus', spec['apparatus']),
            ('chemicals', spec['chemicals']),
            ('setup', collections.OrderedDict([('vessels', spec['vessels'])])),
            ('steps', steps),
            ('safety', collections.OrderedDict([('level', spec['safety'][0]), ('en', spec['safety'][1]), ('bn', spec['safety'][2])])),
            ('expectedReactions', spec['reactions']),
            ('quiz', [collections.OrderedDict([('question_en', q[0]), ('question_bn', q[1]), ('options_en', q[2]),
                                              ('options_bn', q[3]), ('answer', q[4]), ('explain_en', q[5]), ('explain_bn', q[6])])
                      for q in QUIZZES[spec['slug']]]),
            ('tags', spec['tags']),
            ('slug', spec['slug']),
            ('title_en', spec['title_en']),
            ('title_bn', spec['title_bn']),
            ('aim_en', spec['aim_en']),
            ('aim_bn', spec['aim_bn'])
        ])
        exps.append(entry)
    exps.sort(key=lambda e: e['order'])
    data['count'] = len(exps)
    with open(exp_path, 'w', encoding='utf-8') as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write('\n')
    print('experiments:', data['count'])


if __name__ == '__main__':
    main()
